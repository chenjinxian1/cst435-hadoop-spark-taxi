#!/usr/bin/env python3
"""Summarise the page-cache experiment (scripts/cache_experiment.sh).

  python scripts/plot_cache.py [--tier L]

Writes
  results/cache/cache_summary.csv     mean/std per engine, workers and mode
  report/figures/cache_effect.pdf     (a) run time cold vs. warm, (b) disk reads in warm runs
  report/generated/cache_table.tex    LaTeX rows for the report
"""
import argparse
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LABELS = {"mr": "Hadoop MR", "spark_df": "Spark DataFrame"}
COLOR = {"mr": "#1f4e79", "spark_df": "#548235"}

plt.rcParams.update({"font.size": 8, "font.family": "serif", "axes.spines.top": False,
                     "axes.spines.right": False, "legend.frameon": False})


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tier", default="L")
    a = ap.parse_args()
    df = pd.read_csv(os.path.join(ROOT, "results", "cache", "cache_runs.csv"))
    df = df[(df.tier == a.tier) & df.seconds.notna()]
    df["data_per_worker"] = df.hdfs_mib_per_worker.astype(str).map(
        lambda s: sum(float(x) for x in s.split(";")) / len(s.split(";")))
    # CPU time withheld by the 2-CPU cap (summed over the CPUs of a worker) per second of run time
    df["throttle_ratio"] = df.cpu_throttled_s / df.nodes / df.seconds
    s = (df.groupby(["framework", "nodes", "mode"])
           .agg(seconds=("seconds", "mean"), seconds_std=("seconds", "std"),
                disk_read_mib=("disk_read_mib", "mean"), refault_mib=("refault_mib", "mean"),
                cache_peak_mib=("cache_peak_mib", "mean"), anon_peak_mib=("anon_peak_mib", "mean"),
                data_per_worker=("data_per_worker", "mean"), throttle_ratio=("throttle_ratio", "mean"),
                runs=("seconds", "count"))
           .reset_index())
    s.to_csv(os.path.join(ROOT, "results", "cache", "cache_summary.csv"), index=False)
    print(s.round(1).to_string(index=False))

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(7.0, 2.2))
    for fw in [f for f in LABELS if f in set(s.framework)]:
        for mode, ls, mk in [("cold", "--", "o"), ("warm", "-", "s")]:
            d = s[(s.framework == fw) & (s["mode"] == mode)].sort_values("nodes")
            ax1.errorbar(d.nodes, d.seconds, yerr=d.seconds_std, color=COLOR[fw], ls=ls, marker=mk,
                         ms=3.5, lw=1.2, capsize=2, label=f"{LABELS[fw]}, {mode}")
            if mode == "warm":
                ax2.plot(d.nodes, d.disk_read_mib / 1024, color=COLOR[fw], marker=mk, ms=3.5, lw=1.2,
                         label=f"{LABELS[fw]}, warm")
    cold = s[s["mode"] == "cold"].groupby("nodes").disk_read_mib.mean() / 1024
    ax2.plot(cold.index, cold.values, color="grey", ls=":", marker="o", ms=3, lw=1,
             label="cold runs (mean)")
    nodes = sorted(s.nodes.unique())
    for ax in (ax1, ax2):
        ax.set_xlabel("Workers")
        ax.set_xticks(nodes)
    ax1.set_ylabel("Run time (s)")
    ax1.set_title(f"(a) routes, tier {a.tier}")
    ax2.set_ylabel("Read from disk (GiB)")
    ax2.set_title("(b) disk reads during the run")
    ax1.legend(fontsize=6.5)
    ax2.legend(fontsize=6.5)
    fig.tight_layout()
    fig.savefig(os.path.join(ROOT, "report", "figures", "cache_effect.pdf"), bbox_inches="tight")

    with open(os.path.join(ROOT, "report", "generated", "cache_table.tex"), "w", encoding="utf-8") as f:
        f.write(f"% generated by scripts/plot_cache.py (tier {a.tier}, job routes)\n")
        for n in nodes:
            row = [str(n), f"{s[s.nodes == n].data_per_worker.mean() / 1024:.2f}"]
            for fw in ["mr", "spark_df"]:
                for mode in ["cold", "warm"]:
                    v = s[(s.framework == fw) & (s.nodes == n) & (s["mode"] == mode)]
                    row.append(f"{v.seconds.iloc[0]:.1f}" if len(v) else "--")
            warm = s[(s.nodes == n) & (s["mode"] == "warm")]
            row.append(f"{warm.disk_read_mib.max():.0f}")
            for fw in ["mr", "spark_df"]:
                v = s[(s.framework == fw) & (s.nodes == n)]
                row.append(f"{v.throttle_ratio.mean():.2f}" if len(v) else "--")
            f.write(" & ".join(row) + " \\\\\n")


if __name__ == "__main__":
    main()
