#!/usr/bin/env python3
"""Aggregate results/benchmark.csv and draw the report figures.

  python scripts/plot_results.py [--csv results/benchmark.csv] [--env local-docker]

Writes
  results/summary.csv               mean/std runtime, speedup, efficiency
  report/figures/runtime_<job>.pdf  runtime vs workers, one panel per tier
  report/figures/speedup_<job>.pdf  relative speedup vs workers (+ ideal line)
  report/generated/summary_table.tex  LaTeX rows: T(N) and speedup metrics, tier L
  report/generated/cloud_table.tex    LaTeX rows: local vs. Azure, tier L
  report/generated/combiner_table.tex LaTeX rows: MR counters with/without combiner

Speedup definitions (both reported):
  relative  S_rel(N) = T_fw(1) / T_fw(N)        (same framework, 1 worker)
  absolute  S_abs(N) = T_serial / T_fw(N)       (single-process Python baseline)
  efficiency E(N)    = S_rel(N) / N
"""
import argparse
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LABELS = {"mr": "Hadoop MR (combiner)", "mr_nocombiner": "Hadoop MR (no combiner)",
          "spark_rdd": "Spark RDD", "spark_df": "Spark DataFrame", "serial": "Serial Python"}
STYLE = {"mr": ("#1f4e79", "o", "-"), "mr_nocombiner": ("#1f4e79", "o", "--"),
         "spark_rdd": ("#c55a11", "s", "-"), "spark_df": ("#548235", "^", "-")}
TIER_ORDER = ["S", "M", "L", "XL"]

plt.rcParams.update({"font.size": 8, "font.family": "serif", "axes.spines.top": False,
                     "axes.spines.right": False, "legend.frameon": False})


def summarise(df):
    ok = df[df.status == "ok"]
    g = (ok.groupby(["env", "framework", "job", "tier", "nodes"])["seconds"]
           .agg(mean="mean", std="std", runs="count").reset_index())
    base1 = g[g.nodes == 1].set_index(["env", "framework", "job", "tier"])["mean"]
    g["speedup_rel"] = [base1.get((e, f, j, t), float("nan")) / m
                        for e, f, j, t, m in zip(g.env, g.framework, g.job, g.tier, g["mean"])]
    g["efficiency"] = g["speedup_rel"] / g["nodes"]
    serial = g[g.framework == "serial"].set_index(["env", "job", "tier"])["mean"]
    g["speedup_abs"] = [serial.get((e, j, t), float("nan")) / m
                        for e, j, t, m in zip(g.env, g.job, g.tier, g["mean"])]
    return g


def plot_job(g, job, outdir):
    d = g[(g.job == job) & (g.framework != "serial")]
    tiers = [t for t in TIER_ORDER if t in set(d.tier)]
    if not tiers:
        return
    for kind, ycol, ylabel in [("runtime", "mean", "Wall-clock time (s)"),
                               ("speedup", "speedup_rel", "Speedup vs. 1 worker")]:
        fig, axes = plt.subplots(1, len(tiers), figsize=(3.4 * len(tiers) / 1.6, 2.2),
                                 sharey=(kind == "speedup"), squeeze=False)
        for ax, tier in zip(axes[0], tiers):
            dt = d[d.tier == tier]
            for fw, (c, mk, ls) in STYLE.items():
                s = dt[dt.framework == fw].sort_values("nodes")
                if s.empty:
                    continue
                yerr = s["std"] if kind == "runtime" else None
                ax.errorbar(s.nodes, s[ycol], yerr=yerr, color=c, marker=mk, ls=ls,
                            ms=3.5, lw=1.2, capsize=2, label=LABELS[fw])
            if kind == "speedup":
                n = sorted(dt.nodes.unique())
                ax.plot(n, n, color="grey", lw=0.8, ls=":", label="Ideal (linear)")
            else:
                ser = g[(g.job == job) & (g.tier == tier) & (g.framework == "serial")]
                if not ser.empty:
                    ax.axhline(ser["mean"].iloc[0], color="grey", lw=0.8, ls=":",
                               label=LABELS["serial"])
            ax.set_title(f"Tier {tier}")
            ax.set_xlabel("Workers")
            ax.set_xticks(sorted(dt.nodes.unique()))
        axes[0][0].set_ylabel(ylabel)
        handles, labels = axes[0][0].get_legend_handles_labels()
        fig.legend(handles, labels, loc="upper center", ncol=3, bbox_to_anchor=(0.5, 1.12))
        fig.tight_layout()
        fig.savefig(os.path.join(outdir, f"{kind}_{job}.pdf"), bbox_inches="tight")
        plt.close(fig)


SHORT = {"mr": "MR", "mr_nocombiner": "MR, no comb.", "spark_rdd": "Spark RDD",
         "spark_df": "Spark DF"}


def karp_flatt(s, n):
    return (1 / s - 1 / n) / (1 - 1 / n)


def latex_table(g, path, tier="L"):
    """One row per job and engine: T(N) for N=1..4, then S_rel, E, S_abs and Karp-Flatt e at N=4."""
    if tier not in set(g.tier):
        tier = [t for t in TIER_ORDER if t in set(g.tier)][-1]
    d = g[g.tier == tier]
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"% generated by scripts/plot_results.py for tier {tier}\n")
        for job in sorted(d.job.unique()):
            ser = d[(d.job == job) & (d.framework == "serial")]["mean"]
            if not ser.empty:
                f.write(f"{job} & Serial & {ser.iloc[0]:.1f} & & & & & & & \\\\\n")
            dj = d[(d.job == job) & (d.framework != "serial")]
            best = dj.groupby("nodes")["mean"].min()          # fastest engine per N -> bold
            best_abs = dj[dj.nodes == dj.nodes.max()].speedup_abs.max()
            for fw in STYLE:
                s = d[(d.job == job) & (d.framework == fw)].set_index("nodes")
                if s.empty:
                    continue
                bf = lambda v, on: f"\\textbf{{{v}}}" if on else v
                t = [bf(f"{s.loc[n, 'mean']:.1f}", s.loc[n, "mean"] == best[n]) if n in s.index else "--"
                     for n in (1, 2, 3, 4)]
                nmax = s.index.max()
                r = s.loc[nmax]
                f.write(f" & {SHORT[fw]} & {' & '.join(t)} & {r.speedup_rel:.2f} & "
                        f"{r.efficiency:.2f} & {bf(f'{r.speedup_abs:.2f}', r.speedup_abs == best_abs)} & "
                        f"{karp_flatt(r.speedup_rel, nmax):.2f} \\\\\n")
            f.write("\\addlinespace\n")


def cloud_table(g, path, tier="L", cloud_env="azure", local_env="local-docker"):
    """Sum of the three jobs on one tier: local containers vs. Azure VMs at N=1 and N=2."""
    d = g[(g.tier == tier) & g.env.isin([local_env, cloud_env])]
    if cloud_env not in set(d.env):
        return
    tot = d.groupby(["env", "framework", "nodes"])["mean"].sum()
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"% generated by scripts/plot_results.py (tier {tier}, sum of the three jobs)\n")
        for fw in ["serial"] + list(STYLE):
            cells = []
            for env in (local_env, cloud_env):
                t1 = tot.get((env, fw, 1), float("nan"))
                t2 = tot.get((env, fw, 2), float("nan"))
                if fw == "serial":
                    cells += [f"{t1:.0f}", "", ""]
                else:
                    cells += [f"{t1:.0f}", f"{t2:.0f}", f"{t1 / t2:.2f}"]
            name = "Serial" if fw == "serial" else SHORT[fw]
            f.write(f"{name} & {' & '.join(cells)} \\\\\n")


WEAK = {1: "W3", 2: "M", 3: "W9", 4: "L"}   # 3 months of data per worker


def plot_weak(g, outdir):
    """Weak-scaling efficiency T(1, W3) / T(N, 3N months), averaged over the three jobs."""
    rows = []
    for (fw, job), d in g[g.framework != "serial"].groupby(["framework", "job"]):
        t = {n: d[(d.nodes == n) & (d.tier == tier)]["mean"] for n, tier in WEAK.items()}
        if t[1].empty:
            continue
        for n in WEAK:
            if not t[n].empty:
                rows.append((fw, job, n, t[1].iloc[0] / t[n].iloc[0]))
    if not rows:
        return
    w = pd.DataFrame(rows, columns=["framework", "job", "nodes", "eff"])
    w = w.groupby(["framework", "nodes"])["eff"].mean().reset_index()
    fig, ax = plt.subplots(figsize=(3.4, 2.2))
    for fw, (c, mk, ls) in STYLE.items():
        s = w[w.framework == fw]
        if not s.empty:
            ax.plot(s.nodes, s.eff, color=c, marker=mk, ls=ls, ms=3.5, lw=1.2, label=LABELS[fw])
    ax.axhline(1, color="grey", lw=0.8, ls=":", label="Ideal")
    ax.set_xlabel("Workers (3 months of data each)")
    ax.set_ylabel("Weak-scaling efficiency")
    ax.set_xticks(sorted(w.nodes.unique()))
    ax.set_ylim(0, 1.15)
    ax.legend(fontsize=6.5)
    fig.tight_layout()
    fig.savefig(os.path.join(outdir, "weak_scaling.pdf"), bbox_inches="tight")
    plt.close(fig)


def combiner_table(path_csv, path_tex, tier="L"):
    if not os.path.exists(path_csv):
        return
    c = pd.read_csv(path_csv)
    c = c[(c.tier == tier) & (c.env == "local-docker")]
    if c.empty:
        return
    m = c.groupby(["job", "framework"])[["map_output_records", "combine_output_records",
                                         "reduce_shuffle_bytes"]].mean().reset_index()
    with open(path_tex, "w", encoding="utf-8") as f:
        f.write(f"% generated by scripts/plot_results.py (tier {tier})\n")
        for job in sorted(m.job.unique()):
            a = m[(m.job == job) & (m.framework == "mr")]
            b = m[(m.job == job) & (m.framework == "mr_nocombiner")]
            if a.empty or b.empty:
                continue
            a, b = a.iloc[0], b.iloc[0]
            f.write(f"{job} & \\num{{{int(a.map_output_records)}}} & \\num{{{int(a.combine_output_records)}}} & "
                    f"{b.reduce_shuffle_bytes / 2**20:.1f} & {a.reduce_shuffle_bytes / 2**20:.3f} \\\\\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", default=os.path.join(ROOT, "results", "benchmark.csv"),
                    help="one or more comma-separated benchmark CSVs (e.g. local + cloud)")
    ap.add_argument("--env", default="local-docker")
    ap.add_argument("--old-figures", action="store_true",
                    help="also draw the first-draft runtime/speedup/weak-scaling figures")
    a = ap.parse_args()
    g = summarise(pd.concat([pd.read_csv(p) for p in a.csv.split(",") if os.path.exists(p)]))
    g.to_csv(os.path.join(ROOT, "results", "summary.csv"), index=False)
    ge = g[g.env == a.env]
    figdir = os.path.join(ROOT, "report", "figures")
    gendir = os.path.join(ROOT, "report", "generated")
    os.makedirs(figdir, exist_ok=True)
    os.makedirs(gendir, exist_ok=True)
    if a.old_figures:   # superseded by scripts/report_figures.py
        for job in sorted(ge.job.unique()):
            plot_job(ge, job, figdir)
        plot_weak(ge, figdir)
    latex_table(ge, os.path.join(gendir, "summary_table.tex"))
    cloud_table(g, os.path.join(gendir, "cloud_table.tex"))
    combiner_table(os.path.join(ROOT, "results", "counters.csv"),
                   os.path.join(gendir, "combiner_table.tex"))
    print(f"wrote results/summary.csv, figures to {figdir}")


if __name__ == "__main__":
    main()
